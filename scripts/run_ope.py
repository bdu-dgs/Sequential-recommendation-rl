"""Off-policy evaluation on SIMULATED logs with KNOWN propensities (step 8).

Target quantity: the one-step value of a deterministic target policy on the logged state distribution,
    V1(pi) = E_{s ~ D}[ r(s, pi(s)) ],
whose ground truth is computed exactly from the simulator (true effective response of the chosen item at the
logged state). Estimators: IPS, SNIPS, DM (reward-regression ranker as q_hat), DR. Diagnostics: Kish ESS, max
weight share, mean weight, and unsupported mass (share of states where pi_b(pi(s)|s) < tau).
Multi-step trajectory OPE is not reported: deterministic 30-step targets give near-zero trajectory weights.

These estimates are valid ONLY because the logging policy and its probabilities were generated by us. They say
nothing about real KuaiRec logs, which have no propensities.
Usage: python scripts/run_ope.py --seed 0
"""

from __future__ import annotations

import argparse

import numpy as np
import torch

from seqrec_rl.replay.buffer import obs_from_batch
from seqrec_rl.training.checkpoints import load_agent
from seqrec_rl.training.runs import Run, limit_threads, load_config, set_seed
from seqrec_rl.training.setup import Setup

TARGETS = [("offline", m) for m in ("ranker", "bc", "dqn", "cql", "calql", "bcq")] + \
          [("online", m) for m in ("scratch_dqn", "ft_dqn", "ft_cql", "ft_support_oracle", "bandit")]


@torch.no_grad()
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/experiment/base.yaml")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--n", type=int, default=50000, help="logged transitions used")
    ap.add_argument("--tau", type=float, default=1e-4)
    ap.add_argument("--tag", default="", help="tag of the runs to evaluate")
    ap.add_argument("overrides", nargs="*")
    args = ap.parse_args()
    cfg = load_config(args.config, args.overrides)
    limit_threads(4)
    set_seed(args.seed)
    run = Run("ope" + (f"_{args.tag}" if args.tag else ""), args.seed, cfg)
    S = Setup(cfg, args.seed)
    buf = S.offline_buffer(generate=False)
    rng = np.random.default_rng(args.seed)
    idx = rng.choice(buf.size, size=min(args.n, buf.size), replace=False)
    lp = S.logging_policy()
    beta, w_len = S.sim_cfg.fatigue_beta, S.sim_cfg.fatigue_window
    tags = torch.as_tensor(S.data.tags, device=S.dev)
    W = torch.as_tensor(S.data.W, device=S.dev)
    ranker = load_agent(S, "offline", "ranker", args.seed, args.tag)

    def true_reward(obs, users, a):
        t = obs["step"].long()
        cols = t[:, None] - torch.arange(1, w_len + 1, device=S.dev)[None, :]
        prev = obs["ep_items"].gather(1, cols.clamp(min=0))
        valid = (cols >= 0) & (prev < S.data.n_items)
        share = (tags[prev.clamp(max=S.data.n_items - 1)] & tags[a][:, None, :]).any(-1) & valid
        return W[users, a] * (1 - beta * share.float().sum(1) / w_len)

    results = {}
    for kind, m in TARGETS:
        agent = load_agent(S, kind, m, args.seed, args.tag)
        if agent is None:
            continue
        acc = {k: [] for k in ("w", "r", "true", "qpi", "qlog", "pb_pi")}
        for s in range(0, len(idx), 2048):
            b = buf.batch(idx[s:s + 2048], S.dev)
            obs = obs_from_batch(b)
            obs_np = {k: v.cpu().numpy() for k, v in obs.items()}
            a_pi = torch.as_tensor(agent.act(obs_np, rng, explore=False), device=S.dev)
            pb = lp.probs_t(obs)
            pb_pi = pb.gather(1, a_pi[:, None]).squeeze(1)
            match = (a_pi == b["action"]).float()
            acc["w"].append(match / b["prop"])
            acc["r"].append(b["reward"])
            acc["true"].append(true_reward(obs, b["user_row"].long(), a_pi))
            q = ranker.net(obs)
            acc["qpi"].append(q.gather(1, a_pi[:, None]).squeeze(1))
            acc["qlog"].append(q.gather(1, b["action"][:, None]).squeeze(1))
            acc["pb_pi"].append(pb_pi)
        v = {k: torch.cat(x).double().cpu().numpy() for k, x in acc.items()}
        w, r = v["w"], v["r"]
        truth = v["true"].mean()
        est = {"IPS": float(np.mean(w * r)),
               "SNIPS": float(np.sum(w * r) / max(np.sum(w), 1e-12)),
               "DM": float(v["qpi"].mean()),
               "DR": float(v["qpi"].mean() + np.mean(w * (r - v["qlog"])))}
        diag = {"ess": float(w.sum() ** 2 / max((w ** 2).sum(), 1e-12)), "n": int(len(w)),
                "max_weight_share": float(w.max() / max(w.sum(), 1e-12)), "mean_weight": float(w.mean()),
                "match_rate": float((w > 0).mean()), "unsupported_mass": float((v["pb_pi"] < args.tau).mean())}
        results[f"{kind}/{m}"] = {"true_V1": float(truth), "estimates": est,
                                  "rel_error": {k: float(abs(e - truth) / abs(truth)) for k, e in est.items()},
                                  "diagnostics": diag}
        print(f"{kind}/{m:20s} true {truth:.3f} " + " ".join(f"{k} {e:.3f}" for k, e in est.items()) +
              f" | ESS {diag['ess']:.0f} unsupported {diag['unsupported_mass']:.3f}")
    run.save_metrics({"results": results, "tau": args.tau,
                      "note": "One-step OPE on simulated logs with known propensities; not applicable to real logs."})


if __name__ == "__main__":
    main()
